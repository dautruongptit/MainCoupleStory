  rootClass?: string;
  /** Class bọc các khối nội dung bên trong (khi decor nằm ngoài root thiệp) */
  innerClass?: string;
  testId: string;
  /** Thứ tự và tập khối được vẽ (tên khớp `blocks/index.ts`) */
